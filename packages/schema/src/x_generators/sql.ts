/**
 * SQL DDL Generator
 * =================
 * Reads ALL_TABLE_CONFIGS (TableConfig[]) and generates TimescaleDB CREATE TABLE,
 * hypertable, compression, and index DDL.
 * Output: packages/schema/generated/001_tables.sql
 *
 * Migrated from TableDef (Phase 3): fieldTypes keys are snake_case column names directly.
 * Also generates compression DDL (ALTER TABLE SET + add_compression_policy) from
 * TableConfig.compression — not available in the old TableDef layer.
 */

import type { TableConfig } from '../utils';

export function generateSql(tables: readonly TableConfig[]): string {
    const lines: string[] = [
        '-- AUTO-GENERATED by @repo/schema — Do not edit manually.',
        '-- Regenerate: pnpm --filter @repo/schema codegen',
        '',
        'CREATE EXTENSION IF NOT EXISTS timescaledb;',
        '',
    ];

    for (const table of tables) {
        lines.push(`-- ── ${table.name} ${'─'.repeat(Math.max(0, 60 - table.name.length))}`);
        lines.push('');

        // CREATE TABLE
        const colDefs = Object.entries(table.fieldTypes).map(
            ([fieldName, sqlType]) => `  ${fieldName.padEnd(18)} ${sqlType}`
        );

        if (table.unique && table.unique.length > 0) {
            colDefs.push(`  UNIQUE (${table.unique.join(', ')})`);
        }

        lines.push(`CREATE TABLE IF NOT EXISTS ${table.name} (`);
        lines.push(colDefs.join(',\n'));
        lines.push(');');
        lines.push('');

        // Hypertable
        if (table.hypertable) {
            lines.push(`SELECT create_hypertable('${table.name}', '${table.hypertable.timeColumn}',`);
            lines.push(`  chunk_time_interval => INTERVAL '${table.hypertable.chunkInterval}',`);
            lines.push('  if_not_exists => TRUE');
            lines.push(');');
            lines.push('');
        }

        // Compression
        if (table.compression) {
            const { segmentBy, orderBy, after } = table.compression;
            const compressOpts: string[] = ['  timescaledb.compress'];
            if (segmentBy) compressOpts.push(`  timescaledb.compress_segmentby = '${segmentBy}'`);
            if (orderBy)   compressOpts.push(`  timescaledb.compress_orderby = '${orderBy}'`);
            lines.push(`ALTER TABLE ${table.name} SET (`);
            lines.push(compressOpts.join(',\n'));
            lines.push(');');
            lines.push(`SELECT add_compression_policy('${table.name}', INTERVAL '${after}', if_not_exists => TRUE);`);
            lines.push('');
        }

        // Indexes
        if (table.indexes) {
            for (const idx of table.indexes) {
                lines.push(`CREATE INDEX IF NOT EXISTS ${idx.name}`);
                lines.push(`  ON ${table.name} (${idx.columns.join(', ')});`);
            }
        }

        lines.push('');
    }

    return lines.join('\n');
}
