/**
 * GraphQL TypeDefs Generator
 * ==========================
 * Reads ALL_TABLE_CONFIGS (TableConfig[]) and generates GraphQL type definitions.
 * Converts snake_case fieldTypes keys to camelCase GraphQL field names.
 * Output: packages/schema/generated/typeDefs.ts
 *
 * Migrated from TableDef (Phase 3): fieldTypes keys are snake_case column names directly.
 * snakeToCamel() converts them to camelCase for GQL field names.
 */

import type { TableConfig } from '../utils';

/** Map SQL types to GraphQL scalar types */
function sqlToGraphQL(sqlType: string): string {
    const upper = sqlType.toUpperCase();
    if (upper.includes('BOOLEAN')) return 'Boolean';
    if (upper.includes('INTEGER') || upper.includes('INT')) return 'Int';
    if (
        upper.includes('NUMERIC') ||
        upper.includes('DOUBLE') ||
        upper.includes('FLOAT')
    )
        return 'Float';
    if (upper.includes('TIMESTAMPTZ') || upper.includes('TIMESTAMP'))
        return 'String';
    return 'String';
}

/** Convert snake_case table name to PascalCase GraphQL type name */
function snakeToPascal(s: string): string {
    return s
        .split('_')
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join('');
}

/** Convert snake_case field name to camelCase GraphQL field name */
function snakeToCamel(s: string): string {
    return s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
}

export function generateGraphQL(tables: readonly TableConfig[]): string {
    const lines: string[] = [
        '// AUTO-GENERATED by @repo/schema — Do not edit manually.',
        '// Regenerate: pnpm --filter @repo/schema codegen',
        '',
        'export const generatedTypeDefs = /* GraphQL */ `',
    ];

    for (const table of tables) {
        const typeName = snakeToPascal(table.name);
        lines.push(`  type ${typeName} {`);

        for (const [fieldName, sqlType] of Object.entries(table.fieldTypes)) {
            const gqlType = sqlToGraphQL(sqlType);
            const nullable = sqlType.includes('NOT NULL') ? '!' : '';
            const camelName = snakeToCamel(fieldName);
            lines.push(`    ${camelName}: ${gqlType}${nullable}`);
        }

        lines.push('  }');
        lines.push('');
    }

    lines.push('`;');
    lines.push('');

    return lines.join('\n');
}
