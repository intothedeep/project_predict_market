/**
 * Python Pydantic Generator
 * =========================
 * Reads ALL_TABLE_CONFIGS and generates Pydantic BaseModel classes.
 * Output: apps/ml_server/src/schemas.py (or packages/schema/generated/schemas.py)
 */

import type { TableConfig } from '../utils';

/** Map SQL types to Python type annotations */
function sqlToPython(sqlType: string): string {
    const upper = sqlType.toUpperCase();
    if (upper.includes('BOOLEAN')) return 'bool';
    if (upper.includes('INTEGER') || upper.includes('INT')) return 'int';
    if (
        upper.includes('NUMERIC') ||
        upper.includes('DOUBLE') ||
        upper.includes('FLOAT')
    )
        return 'float';
    if (upper.includes('TIMESTAMPTZ') || upper.includes('TIMESTAMP'))
        return 'datetime';
    return 'str';
}

/** Convert snake_case to PascalCase */
function snakeToPascal(s: string): string {
    return s
        .split('_')
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join('');
}

export function generatePython(tables: readonly TableConfig[]): string {
    const lines: string[] = [
        '"""',
        'AUTO-GENERATED by @repo/schema — Do not edit manually.',
        'Regenerate: pnpm --filter @repo/schema codegen',
        '"""',
        '',
        'from __future__ import annotations',
        '',
        'from datetime import datetime',
        'from typing import Optional',
        '',
        'from pydantic import BaseModel',
        '',
    ];

    for (const table of tables) {
        const className = snakeToPascal(table.name);
        lines.push('');
        lines.push(`class ${className}(BaseModel):`);
        lines.push(`    """Schema for table: ${table.name}"""`);
        lines.push('');

        for (const [fieldName, sqlType] of Object.entries(table.fieldTypes)) {
            const pyType = sqlToPython(sqlType);
            const isRequired = sqlType.includes('NOT NULL');

            if (isRequired) {
                lines.push(`    ${fieldName}: ${pyType}`);
            } else {
                lines.push(`    ${fieldName}: Optional[${pyType}] = None`);
            }
        }

        lines.push('');
    }

    return lines.join('\n');
}
